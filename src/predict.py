"""
predict.py -- Prediction module for heart disease risk classification.

Handles:
- Loading the trained model and preprocessing pipeline
- Single patient prediction from a dictionary of features
- Batch prediction from a CSV file
- Risk category assignment based on model probability output
- Input validation
- Clear disclaimers on every prediction

Risk Categories (based on model probability output):
- Low Risk:     P(disease) < 0.35
- Moderate Risk: 0.35 <= P(disease) < 0.65
- High Risk:    P(disease) >= 0.65

DISCLAIMER: These categories are statistical groupings from the model's
output. They are NOT clinically validated risk scores and should NOT be
used for medical decisions.
"""

